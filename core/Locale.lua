-- @ADDON@: languages (shared texts; class texts are in LocaleClass.lua). English is the default; Swedish can be picked in the menu.
local _, ns = ...

local E, S = {}, {}
ns.LOCALES = { enUS = E, svSE = S }
ns.LANGS = { { key = "enUS", name = "English" }, { key = "svSE", name = "Svenska" } }

function ns.Lang()
  return (@ADDON@Global and @ADDON@Global.lang) or "enUS"
end

-- Translated string, formatted with any extra arguments.
function ns.T(key, ...)
  local L = ns.LOCALES[ns.Lang()]
  -- A text can have a version for the chosen talent plan: KEY@plan (e.g. UP_UP@holy).
  local tag = ns.planTag and (key .. ns.planTag)
  local s = (tag and (L[tag] or E[tag])) or L[key] or E[key] or key
  if select("#", ...) > 0 then return string.format(s, ...) end
  return s
end

-- Data entries: a plain string, or { "English", "Svenska" }.
function ns.Tx(entry)
  if type(entry) == "table" then
    return (ns.Lang() == "svSE" and entry[2]) or entry[1]
  end
  return entry
end

