-- Writes core/ZoneData.lua: which zones to level in, per faction, from QuestieDB's WoW Forever
-- quests. A zone's range is the 20th to 80th percentile of its quest levels; its hub is where
-- most of its quest givers stand (for the arrow).
--   QDB=path/to/QuestieDB texlua tools/genzones.lua AreaTable.csv
-- (AreaTable.csv from wago.tools gives the English zone names, the fallback when the game has none.)
dofile("tools/qload.lua")
local QDB = os.getenv("QDB") or "QDB"
local C = QDB .. "/src/corrections/Forever/combined/"
local Q = dofile(C .. "foreverQuestDB.lua")
local N = dofile(C .. "foreverNpcDB.lua")
local Z = QDB .. "/support/Forever/Zones/areaIdToUiMapId.lua"
local toUi = QLoad(Z, "ZoneDB.private.areaIdToUiMapId")
for k, v in pairs(QLoad(Z, "ZoneDB.private.areaIdToUiMapIdOverride")) do toUi[k] = v end

-- Not leveling zones: dungeons and raids (Questie's dungeon list), capitals, battlegrounds and
-- Questie's "Crafting" group.
local SKIP = { [1519] = true, [1537] = true, [1657] = true, [1637] = true, [1638] = true, [1497] = true,
  [3277] = true, [3358] = true, [2597] = true, [16941] = true, [25] = true }
local dsrc = io.open(QDB .. "/support/Forever/Zones/dungeons.lua"):read("a")
for id, rest in dsrc:gmatch("%[(%d+)%] = {\"[^\"]+\",([^\n]*)") do
  SKIP[tonumber(id)] = true
  local alt = rest:match("^(%b{})")
  if alt then for a in alt:gmatch("%d+") do SKIP[tonumber(a)] = true end end
end

local names = {}
local csvPath = assert(arg[1], "usage: genzones.lua AreaTable.csv")
for line in io.open(csvPath):read("a"):gmatch("[^\n]+") do
  local id, n = line:match('^(%d+),[^,]*,"?([^",]+)')
  if id then names[tonumber(id)] = n end
end

local ALLY, HORDE = 4294967373, 8589934770
local zones = { A = {}, H = {} }
for _, q in pairs(Q) do
  local zone, lvl, r = q[17], q[5] or q[4], q[6] or 0
  if zone and zone > 0 and not SKIP[zone] and toUi[zone] and toUi[zone] ~= 0 and lvl and lvl > 0
      and not (q[7] and q[7] ~= 0) and not (q[18] or q[31] or q[35]) then
    for _, f in ipairs({ "A", "H" }) do
      local mask = f == "A" and ALLY or HORDE
      if r == 0 or (r & mask) ~= 0 then
        local z = zones[f][zone] or { lv = {}, pts = {} }
        zones[f][zone] = z
        z.lv[#z.lv + 1] = lvl
        for _, npc in ipairs(q[2] and q[2][1] or {}) do
          local n = N[npc]
          local sp = n and (not n[13] or n[13]:find(f)) and n[7] and n[7][zone]
          if sp and sp[1] and sp[1][1] and sp[1][1] > 0 then z.pts[#z.pts + 1] = sp[1] end
        end
      end
    end
  end
end

local function hub(pts)
  local cells, best = {}, nil
  for _, p in ipairs(pts) do
    local k = math.floor(p[1] / 6) .. ":" .. math.floor(p[2] / 6)
    cells[k] = cells[k] or {}
    table.insert(cells[k], p)
    if not best or #cells[k] > #cells[best] then best = k end
  end
  if not best then return nil end
  local x, y = 0, 0
  for _, p in ipairs(cells[best]) do x, y = x + p[1], y + p[2] end
  return x / #cells[best], y / #cells[best]
end

local out = {
  "-- @ADDON@: zones to level in, per faction: { area ID, low, high, uiMap, hub x, hub y, English name }.",
  "-- From QuestieDB's WoW Forever quests (https://github.com/Questie/QuestieDB, GPL-3.0).",
  "-- Generated by tools/genzones.lua. Do not edit by hand.",
  "local _, ns = ...", "", "ns.LEVEL_ZONES = {",
}
for _, f in ipairs({ "A", "H" }) do
  local rows = {}
  for zone, z in pairs(zones[f]) do
    if #z.lv >= 12 then
      table.sort(z.lv)
      local lo, hi = z.lv[math.floor(#z.lv * 0.2) + 1], z.lv[math.floor(#z.lv * 0.8)]
      local x, y = hub(z.pts)
      if x and hi >= lo then rows[#rows + 1] = { zone, lo, hi, toUi[zone], x, y, #z.lv } end
    end
  end
  table.sort(rows, function(a, b) if a[2] ~= b[2] then return a[2] < b[2] end return a[7] > b[7] end)
  out[#out + 1] = "  " .. f .. " = {"
  for _, r in ipairs(rows) do
    out[#out + 1] = string.format("    { %d, %d, %d, %d, %.1f, %.1f, %q }, -- %d quests", r[1], r[2], r[3], r[4], r[5], r[6], names[r[1]] or "?", r[7])
  end
  out[#out + 1] = "  },"
  print(f, #rows .. " zones")
end
out[#out + 1] = "}"
local fh = io.open("core/ZoneData.lua", "w"); fh:write(table.concat(out, "\n") .. "\n"); fh:close()
