"""Writes core/SpellIds.lua: English spell name -> spell ID, so the addon works in any client language.

python3 tools/genspellids.py path/to/SpellName.csv

SpellName.csv is the SpellName table of the current WoW Forever build from wago.tools
(https://wago.tools/db2/SpellName/csv?build=<build>, the build forge's data uses). The names come
from the addon itself: talent trees, trainer ranks, the spell lists and every quoted name in the
Lua code that is also a spell. For each name the lowest ID with exactly that name is kept.
"""
import csv, glob, json, re, sys

src = sys.argv[1]
build = re.search(r'(\d+\.\d+\.\d+\.\d+)', open(glob.glob('tools/trees/*.lua')[0]).readline())
names = set()
for f in glob.glob('tools/trees/*.lua'):
    names |= set(re.findall(r'\["([^"]+)"\] = \{ tree', open(f).read()))
for f in glob.glob('core/*.lua') + glob.glob('classes/*/*.lua'):
    if f.endswith(('SpellIds.lua', 'CampfireLines.lua', 'DungeonData.lua', 'Emotes.lua')):
        continue
    names |= set(re.findall(r'"([A-Z][^"\n]{1,40})"', open(f, encoding='utf8').read()))
ids = {}
with open(src, newline='', encoding='utf8') as fh:
    for row in csv.DictReader(fh):
        n, i = row['Name_lang'], int(row['ID'])
        if n in names and (n not in ids or i < ids[n]):
            ids[n] = i
L = ['-- @ADDON@: spell IDs by English name, so the addon can find spells, auras and talents in any',
     '-- client language (ns.Loc / ns.Eng in Core.lua). From the SpellName table of WoW Forever build',
     '-- %s, the lowest ID with that name. Generated by tools/genspellids.py.' % (build.group(1) if build else '?'),
     'local _, ns = ...', '', 'ns.SPELL_IDS = {']
for n in sorted(ids):
    L.append('  [%s] = %d,' % (json.dumps(n), ids[n]))
L.append('}')
open('core/SpellIds.lua', 'w').write('\n'.join(L) + '\n')
print(len(ids), 'names')
