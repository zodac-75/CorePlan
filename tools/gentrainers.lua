-- Writes core/TrainerData.lua: map position of every profession trainer named in core/ProfData.lua.
--   QDB=path/to/QuestieDB texlua tools/gentrainers.lua
-- (run QuestieDB's tools/export-forever.lua --include-authored first, see CLAUDE.md)
dofile("tools/qload.lua")
local QDB = os.getenv("QDB") or "QDB"
local N = dofile(QDB .. "/src/corrections/Forever/combined/foreverNpcDB.lua")
local Z = QDB .. "/support/Forever/Zones/areaIdToUiMapId.lua"
local toUi = QLoad(Z, "ZoneDB.private.areaIdToUiMapId")
for k, v in pairs(QLoad(Z, "ZoneDB.private.areaIdToUiMapIdOverride")) do toUi[k] = v end

local byName = {}
for id, n in pairs(N) do
  if n[1] and n[7] then byName[n[1]] = byName[n[1]] or {}; table.insert(byName[n[1]], { id = id, sp = n[7] }) end
end

local src = io.open("core/ProfData.lua"):read("a")
local a = src:find("ns.PROF_TRAINERS = {", 1, true)
local b = src:find("\n}\n", a, true)
local names, order = {}, {}
for name in src:sub(a, b):gmatch("([%a'%. %-]-) %(") do
  name = name:gsub("^%s*/%s*", ""):gsub("^%s+", ""):gsub("%s+$", "")
  if name ~= "" and not names[name] then names[name] = true; order[#order + 1] = name end
end
table.sort(order)

local function pick(list)
  for _, c in ipairs(list) do
    local zones = {}
    for z in pairs(c.sp) do zones[#zones + 1] = z end
    table.sort(zones)
    for _, z in ipairs(zones) do
      local ui, p = toUi[z], c.sp[z][1]
      if ui and ui ~= 0 and p and p[1] and p[1] > 0 then return { ui, p[1], p[2] }, #list end
    end
  end
end

local L, miss, multi = {}, {}, {}
for _, name in ipairs(order) do
  local r, cnt
  if byName[name] then r, cnt = pick(byName[name]) end
  if r then
    L[#L + 1] = string.format("  [%q] = { %d, %.1f, %.1f },", name, r[1], r[2], r[3])
    if cnt > 1 then multi[#multi + 1] = name end
  else miss[#miss + 1] = name end
end
local f = io.open("core/TrainerData.lua", "w")
f:write("-- Generated by tools/gentrainers.lua from QuestieDB (Forever). Do not edit by hand.\n")
f:write("-- Profession trainer name -> { uiMapID, x, y } (percent), for the arrow in the plan window.\n")
f:write("local _, ns = ...\nns.TRAINER_POS = {\n" .. table.concat(L, "\n") .. "\n}\n")
f:close()
print(#order .. " names, " .. #L .. " found")
print("missing: " .. table.concat(miss, "; "))
print("several matches (first used): " .. table.concat(multi, "; "))

-- Class trainers (every "<Class> Trainer" with a spawn), for the arrow on the "can train" row.
local CLASSES = { "Druid", "Hunter", "Mage", "Paladin", "Priest", "Rogue", "Shaman", "Warlock", "Warrior" }
local want = {}
for _, c in ipairs(CLASSES) do want[c .. " Trainer"] = c:upper() end
local rows = {}
for id, n in pairs(N) do
  local c = n[14] and want[n[14]]
  if c and n[7] and n[1] then
    local zones = {}
    for z in pairs(n[7]) do zones[#zones + 1] = z end
    table.sort(zones)
    for _, z in ipairs(zones) do
      local ui, pt = toUi[z], n[7][z][1]
      if ui and ui ~= 0 and pt and pt[1] and pt[1] > 0 then
        rows[#rows + 1] = { c = c, id = id, name = n[1], fac = n[13], ui = ui, x = pt[1], y = pt[2] }
        break
      end
    end
  end
end
table.sort(rows, function(a, b) if a.c ~= b.c then return a.c < b.c end return a.id < b.id end)
local O, per = {}, {}
for _, r in ipairs(rows) do
  per[r.c] = (per[r.c] or 0) + 1
  O[#O + 1] = string.format("  { %q, %q, %d, %.1f, %.1f, %s },", r.c, r.name, r.ui, r.x, r.y, r.fac and string.format("%q", r.fac) or "nil")
end
local f2 = io.open("core/ClassTrainerData.lua", "w")
f2:write("-- Generated by tools/gentrainers.lua from QuestieDB (Forever). Do not edit by hand.\n")
f2:write("-- Class trainers: { CLASS, name, uiMapID, x, y, friendly to (\"A\", \"H\", \"AH\") } for the arrow on the train row.\n")
f2:write("local _, ns = ...\nns.CLASS_TRAINERS = {\n" .. table.concat(O, "\n") .. "\n}\n")
f2:close()
local parts = {}
for _, c in ipairs(CLASSES) do parts[#parts + 1] = c .. "=" .. (per[c:upper()] or 0) end
print("class trainers: " .. #rows .. " (" .. table.concat(parts, " ") .. ")")
