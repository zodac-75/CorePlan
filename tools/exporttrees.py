#!/usr/bin/env python3
"""Exports talent trees from the forge client data to tools/trees/<class>.lua for
tools/checktalents.lua.  python3 tools/exporttrees.py path/to/forge/public/data/classes"""
import json, os, sys

src = sys.argv[1]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "trees")
for cls in ("mage", "shaman", "druid", "warrior", "paladin"):
    d = json.load(open(os.path.join(src, cls + ".json"), encoding="utf-8"))
    names = {t["id"]: t["name"] for tree in d["trees"] for t in tree["talents"]}
    lines = ["-- %s talent trees, build %s. Generated by tools/exporttrees.py." % (cls, d["build"]), "return {"]
    for tree in d["trees"]:
        for t in tree["talents"]:
            p = t["prereq"]
            pre = "nil" if not p else '{ %s, %d }' % (json.dumps(names[p["id"]]), p["rank"])
            lines.append('  [%s] = { tree = %s, req = %d, max = %d, prereq = %s },' % (
                json.dumps(t["name"]), json.dumps(tree["name"]), t["req"], len(t["ranks"]), pre))
    lines.append("}")
    open(os.path.join(out, cls + ".lua"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(cls, sum(len(tr["talents"]) for tr in d["trees"]))
