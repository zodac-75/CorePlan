"""Writes core/AreaIds.lua: English zone name -> area IDs, so zone tips work in any client language.

python3 tools/genareaids.py path/to/AreaTable.csv

AreaTable.csv is the AreaTable of the current WoW Forever build from wago.tools
(https://wago.tools/db2/AreaTable?build=<build>, the CSV button). Only the names that zone tips
use (zone = "..." in core/ZoneTips.lua and the class Data.lua files) are kept, with every area
that has exactly that name. In game, C_Map.GetAreaInfo(id) gives the name in the client language.
"""
import csv, glob, re, sys

names = set()
for f in ['core/ZoneTips.lua'] + glob.glob('classes/*/Data.lua'):
    names |= set(re.findall(r'zone = "([^"]+)"', open(f, encoding='utf8').read()))
ids = {}
with open(sys.argv[1], newline='', encoding='utf8') as fh:
    for row in csv.DictReader(fh):
        if row['AreaName_lang'] in names:
            ids.setdefault(row['AreaName_lang'], []).append(int(row['ID']))
missing = sorted(names - set(ids))
if missing:
    sys.exit('not in AreaTable (use the exact area name): ' + ', '.join(missing))
build = re.search(r'(\d+\.\d+\.\d+\.\d+)', sys.argv[1])
L = ['-- @ADDON@: area IDs by English zone name, so zone tips work in any client language',
     '-- (C_Map.GetAreaInfo gives the client name). From the AreaTable of WoW Forever build %s.' % (build.group(1) if build else '?'),
     '-- Generated by tools/genareaids.py.',
     'local _, ns = ...', '', 'ns.AREA_IDS = {']
for n in sorted(ids):
    L.append('  ["%s"] = { %s },' % (n, ', '.join(map(str, sorted(ids[n])))))
L.append('}')
open('core/AreaIds.lua', 'w').write('\n'.join(L) + '\n')
print(len(ids), 'zones')
